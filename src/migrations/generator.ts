import fs from "node:fs/promises";
import path from "node:path";
import { AppError } from "@veap/kernel";

const stub = `import type { Schema } from "@veap/database";

export default {
  name: "{{name}}",
  async up(_db: any, schema: Schema) {
    await schema.createTable("{{tableName}}", (table) => {
      table.increments("id");

      table.timestamps();
    });
  },
  async down(_db: any, schema: Schema) {
    await schema.dropTableIfExists("{{tableName}}");
  },
};
`;

/** Migration names end up in a file name and in a table name, so keep them boring. */
const NAME_PATTERN = /^[a-zA-Z0-9_]+$/;

async function updateIndexFile(migrationsDir: string) {
  const indexFile = path.join(migrationsDir, "index.ts");

  const files = await fs.readdir(migrationsDir);
  const migrationFiles = files
    .filter((f) => f.endsWith(".ts") && f !== "index.ts")
    .sort();

  const imports: string[] = [];
  const normalisers: string[] = [];
  const exports: string[] = [];

  for (const file of migrationFiles) {
    const name = file.replace(".ts", "");
    const varName = `m${name.replace(/[^a-zA-Z0-9]/g, "_")}`;
    // A migration is either the scaffolded `export default { … }` object or a
    // module with named `name`/`up`/`down` exports (every hand-written migration
    // in the shipped apps). Importing the namespace and unwrapping `default`
    // keeps both working, so regenerating the index never silently breaks a
    // migration that was written by hand.
    imports.push(`import * as ${varName}Raw from "./${name}";`);
    normalisers.push(
      `const ${varName} = (${varName}Raw as { default?: unknown }).default ?? ${varName}Raw;`,
    );
    exports.push(varName);
  }

  const content = `// This file is auto-generated by Veap CLI. Do not edit manually.
${imports.join("\n")}

${normalisers.join("\n")}

export const appMigrations = [
  ${exports.join(",\n  ")}
];
`;

  await fs.writeFile(indexFile, content, "utf-8");
}

export interface GeneratedMigration {
  /** Timestamped file name without the extension, e.g. `20261014120000_create_posts_table`. */
  fileName: string;
  /** Absolute path of the written migration file. */
  filePath: string;
}

/**
 * Writes a new migration file and regenerates the directory's `index.ts`.
 *
 * Used by the `veap make:migration` command; kept free of the console so it can
 * be called from anywhere (tests, generators, plugins).
 */
export async function generateMigration(
  name: string,
  targetDir?: string,
): Promise<GeneratedMigration> {
  const trimmed = (name ?? "").trim();
  if (!trimmed) {
    throw AppError.BadRequest("A migration name is required.");
  }
  if (!NAME_PATTERN.test(trimmed)) {
    throw AppError.BadRequest(
      `The migration name "${trimmed}" may only contain letters, digits and underscores.`,
    );
  }

  const timestamp = new Date().toISOString().replace(/[-:T]/g, "").slice(0, 14);
  const fileName = `${timestamp}_${trimmed}`;

  let tableName = trimmed;
  if (trimmed.startsWith("create_") && trimmed.endsWith("_table")) {
    tableName = trimmed.replace("create_", "").replace("_table", "");
  }

  const content = stub
    .replace(/{{name}}/g, fileName)
    .replace(/{{tableName}}/g, tableName);

  const migrationsDir = targetDir || path.join(process.cwd(), "migrations");

  await fs.mkdir(migrationsDir, { recursive: true });

  const filePath = path.join(migrationsDir, `${fileName}.ts`);

  // Two runs inside the same second would otherwise overwrite the first file.
  try {
    await fs.access(filePath);
    throw AppError.Conflict(
      `The migration "${fileName}" already exists at ${filePath}.`,
    );
  } catch (error) {
    if (error instanceof AppError) throw error;
    // ENOENT: nothing to overwrite, keep going.
  }

  await fs.writeFile(filePath, content, "utf-8");

  await updateIndexFile(migrationsDir);

  return { fileName, filePath };
}
